#!/usr/bin/env python3
"""
Bakes TrueType fonts into GameCube-ready I4 (4-bit intensity) tiled textures
and writes source/font_data.h.

Usage:
    python3 tools/make_font.py [ui_bold.ttf] [body.ttf] [italic.ttf] [mono.ttf]

Defaults to DejaVu Sans Bold (UI and bold text), DejaVu Sans (page text),
DejaVu Sans Oblique (italic) and DejaVu Sans Mono (code). For a rounder,
more "Nintendo-era" UI, download an open-licensed rounded font such as
Nunito-Bold.ttf or MPLUSRounded1c-Bold.ttf and pass it as the first argument.

Requires Pillow (pip install pillow).
"""
import sys, os
from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 32, 126
TEX_W, TEX_H = 512, 256

def find(paths):
    for p in paths:
        if os.path.exists(p):
            return p
    return None

def bake(ttf, px, name):
    font = ImageFont.truetype(ttf, px)
    ascent, descent = font.getmetrics()
    line = ascent + descent
    img = Image.new("L", (TEX_W, TEX_H), 0)
    draw = ImageDraw.Draw(img)
    x, y, row_h = 1, 1, 0
    glyphs = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        adv = font.getlength(ch)
        x0, y0, x1, y1 = font.getbbox(ch, anchor="la")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        if w == 0 or h == 0:
            glyphs.append((0, 0, 0, 0, 0, 0, adv))
            continue
        if x + w + 2 > TEX_W:
            x, y = 1, y + row_h + 2
            row_h = 0
        if y + h + 1 > TEX_H:
            raise SystemExit(f"{name}: atlas too small, lower the pixel size")
        draw.text((x - x0, y - y0), ch, font=font, fill=255, anchor="la")
        glyphs.append((x, y, w, h, x0, y0, adv))
        x += w + 2
        row_h = max(row_h, h)

    # Convert to GX I4 tiled format: 8x8 tiles, 4 bits per pixel, 32 bytes/tile
    px_data = img.load()
    out = bytearray()
    for ty in range(0, TEX_H, 8):
        for tx in range(0, TEX_W, 8):
            for yy in range(8):
                for xx in range(0, 8, 2):
                    a = px_data[tx + xx, ty + yy] >> 4
                    b = px_data[tx + xx + 1, ty + yy] >> 4
                    out.append((a << 4) | b)
    return glyphs, out, line, ascent

def emit(f, name, px, glyphs, tex, line, ascent):
    up = name.upper()
    f.write(f"#define FONT_{up}_PX {px}\n#define FONT_{up}_LINE {line}\n#define FONT_{up}_ASCENT {ascent}\n")
    f.write(f"static const FontGlyph font_{name}_glyphs[{len(glyphs)}] = {{\n")
    for g in glyphs:
        f.write("  {%d,%d,%d,%d,%d,%d,%.3ff},\n" % g)
    f.write("};\n")
    f.write(f"static const unsigned char font_{name}_tex[{len(tex)}] __attribute__((aligned(32))) = {{\n")
    for i in range(0, len(tex), 32):
        f.write(",".join(str(b) for b in tex[i:i + 32]) + ",\n")
    f.write("};\n\n")

def main():
    here = os.path.dirname(os.path.abspath(__file__))
    defaults = [
        ["/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", "DejaVuSans-Bold.ttf"],
        ["/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", "DejaVuSans.ttf"],
        ["/usr/share/fonts/truetype/dejavu/DejaVuSans-Oblique.ttf", "DejaVuSans-Oblique.ttf"],
        ["/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf", "DejaVuSansMono.ttf"],
    ]
    paths = []
    for i, d in enumerate(defaults):
        paths.append(sys.argv[i + 1] if len(sys.argv) > i + 1 else find(d))
    if not all(paths):
        raise SystemExit("Font files not found; pass paths as arguments.")
    out_path = os.path.join(here, "..", "source", "font_data.h")
    with open(out_path, "w") as f:
        f.write("/* Generated by tools/make_font.py - do not edit. */\n#pragma once\n")
        f.write(f"#define FONT_TEX_W {TEX_W}\n#define FONT_TEX_H {TEX_H}\n")
        f.write("typedef struct { unsigned short x, y; unsigned char w, h; signed char xoff, yoff; float adv; } FontGlyph;\n\n")
        for name, path, px in (("ui", paths[0], 28), ("body", paths[1], 26),
                               ("italic", paths[2], 26), ("mono", paths[3], 24)):
            glyphs, tex, line, ascent = bake(path, px, name)
            emit(f, name, px, glyphs, tex, line, ascent)
            print(f"{name}: {os.path.basename(path)} {px}px, line {line}")
    print("wrote", os.path.normpath(out_path))

if __name__ == "__main__":
    main()
